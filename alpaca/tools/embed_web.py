#!/usr/bin/env python3
"""
Embeds alpaca/web/ into alpacad as gzip-compressed C arrays.

    embed_web.py <web dir> <output .c>

Each file is stored pre-compressed and served with Content-Encoding: gzip, so
the device needs no zlib -- the browser decompresses. Compression is
deterministic (mtime 0, no filename), so an unchanged web/ produces a
byte-identical .c and an unchanged binary. The ETag is a hash of the
uncompressed content.

The output is generated: edit web/, not the .c.
"""
import gzip
import hashlib
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
}


def main():
    web, out = sys.argv[1], sys.argv[2]
    entries = []
    for root, _, files in os.walk(web):
        for name in sorted(files):
            full = os.path.join(root, name)
            rel = os.path.relpath(full, web).replace(os.sep, "/")
            ext = os.path.splitext(name)[1].lower()
            if ext not in MIME:
                continue
            raw = open(full, "rb").read()
            gz = gzip.compress(raw, compresslevel=9, mtime=0)
            etag = '"%s"' % hashlib.sha1(raw).hexdigest()[:16]
            entries.append((rel, MIME[ext], gz, etag, len(raw)))
    entries.sort()

    lines = [
        "/* GENERATED by tools/embed_web.py from web/ -- do not edit. */",
        '#include "web.h"',
        "",
    ]
    for i, (rel, mime, gz, etag, rawlen) in enumerate(entries):
        lines.append("/* %s: %d bytes, %d gzipped */" % (rel, rawlen, len(gz)))
        lines.append("static const unsigned char a%d[] = {" % i)
        for j in range(0, len(gz), 16):
            lines.append("\t" + ",".join("0x%02x" % b for b in gz[j:j + 16]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("const web_asset_t web_assets[] = {")
    for i, (rel, mime, gz, etag, rawlen) in enumerate(entries):
        lines.append('\t{ "%s", "%s", %s, a%d, %d },' % (
            rel, mime, '"\\"%s\\""' % etag.strip('"'), i, len(gz)))
    lines.append("\t{ 0, 0, 0, 0, 0 },")
    lines.append("};")
    tmp = out + ".tmp"
    open(tmp, "w").write("\n".join(lines) + "\n")
    os.replace(tmp, out)
    total = sum(len(e[2]) for e in entries)
    print("embed_web: %d files, %d bytes gzipped -> %s" % (len(entries), total, out))


if __name__ == "__main__":
    main()
